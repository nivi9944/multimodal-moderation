SH_HELPER = """# Shell helper: prints each step with elapsed time and stops the run if a required step fails
from IPython import get_ipython
import time as _t
_T0 = _t.time()
def sh(cmd, required=True):
    ip = get_ipython()
    cmd = ip.var_expand(cmd, depth=1)
    print(f"\\n$ {cmd}   [t+{(_t.time() - _T0) / 60:.1f} min]", flush=True)
    ip.system(cmd)
    code = ip.user_ns.get("_exit_code", 0)
    if code != 0:
        msg = f"FAILED ({code}): {cmd}"
        print(msg, flush=True)
        if required:
            raise RuntimeError(msg)"""

# steps whose failure should not stop the run (optional extras or recoverable later)
SOFT = (
    "--model roberta-base",
    "clip_probe",
    "merge_results",
    "train_yolo",
    "infer_yolo",
    "pip -q install ultralytics",
    "detector_eval.json",
)


def harden(nb: nbf.NotebookNode) -> nbf.NotebookNode:
    """Replace `!cmd` lines with sh('cmd') so a failed step stops Run All instead of silently continuing."""
    for cell in nb.cells:
        if cell.cell_type != "code":
            continue
        lines = []
        for line in cell.source.splitlines():
            stripped = line.lstrip()
            if stripped.startswith("!"):
                indent = line[: len(line) - len(stripped)]
                cmd = stripped[1:].replace("\\", "\\\\").replace("'", "\\'")
                soft = any(k in cmd for k in SOFT)
                line = f"{indent}sh('{cmd}'{', required=False' if soft else ''})"
            lines.append(line)
        cell.source = "\n".join(lines)
    nb.cells.insert(2, code(SH_HELPER))
    return nb


def collect() -> dict[str, str]:
    files = {}
    for pattern in ("src/**/*.py", "scripts/*.py"):
        for p in sorted(ROOT.glob(pattern)):
            if p.name == "build_notebooks.py":
                continue
            files[str(p.relative_to(ROOT)).replace("\\", "/")] = p.read_text(encoding="utf-8")
    return files


def md(s):
    return nbf.v4.new_markdown_cell(s)


def code(s):
    return nbf.v4.new_code_cell(s)


def notebook(cells) -> nbf.NotebookNode:
    nb = nbf.v4.new_notebook()
    nb.cells = cells
    nb.metadata = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
        "accelerator": "GPU",
    }
    return nb


