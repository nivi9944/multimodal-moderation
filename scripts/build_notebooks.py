def main() -> None:
    files = collect()
    out = ROOT / "notebooks"
    out.mkdir(exist_ok=True)
    nbf.write(harden(text_notebook(files)), out / "kaggle_train_text.ipynb")
    nbf.write(harden(image_notebook(files)), out / "kaggle_train_image.ipynb")
    print(f"embedded {len(files)} files into notebooks/")


if __name__ == "__main__":
    main()
